    // O	0x20300	0x203ff	RAM (banco 1)	0x9e00	0x9fff
    // start = ftell( sddrive );
    for( int i=0x20300; i<=0x203ff; ++i ) {
        char zero = 0;
        fwrite( &zero, 1, 1, sddrive );;
    }
    // end = ftell( sddrive )-1;

    // printf( "O -- 0x%4.4x  0x%4.4x  | RAM (banco 1)\n", start, end );

